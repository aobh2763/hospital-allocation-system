import numpy as np, pandas as pd, torch, torch.nn as nn
from torch.utils.data import TensorDataset, DataLoader
from sklearn.metrics import classification_report, confusion_matrix, f1_score

CSV = "/content/synthetic_emergency_timeseries_2000_patients.csv"
FEATURES = ["HR", "MAP", "SpO2", "Temp", "RespRate", "Lactate"]
NIVEAUX = ["Low", "Medium", "High", "Critical"]
HIDDEN, EPOCHS, LR, BATCH, PATIENCE = 64, 40, 1e-3, 64, 6
SEEDS = [0, 1, 2]


def construire_sequences(df, T):
    X, y, split = [], [], []
    for _, g in df.groupby("Patient_ID"):
        a = g[FEATURES].to_numpy(dtype=np.float32)
        if len(a) < T:
            a = np.vstack([a, np.repeat(a[-1:], T - len(a), axis=0)])
        X.append(a[:T])
        y.append(NIVEAUX.index(g["Risk"].iloc[-1]))
        split.append(str(g["Split"].iloc[0]).lower())
    return np.array(X), np.array(y), np.array(split)


def preparer():
    df = pd.read_csv(CSV).sort_values(["Patient_ID", "Time_Step"])
    df[FEATURES] = df.groupby("Patient_ID")[FEATURES].ffill()
    T = int(df.groupby("Patient_ID").size().median())
    X, y, split = construire_sequences(df, T)
    tr, va, te = (split == "train"), (split == "validation"), (split == "test")
    med = np.nanmedian(X[tr].reshape(-1, X.shape[2]), axis=0)
    X = np.where(np.isnan(X), med, X)
    mu = X[tr].reshape(-1, X.shape[2]).mean(0)
    sd = X[tr].reshape(-1, X.shape[2]).std(0) + 1e-6
    X = (X - mu) / sd
    prep = {"T": T, "med": med, "mu": mu, "sd": sd}
    return {"X": X, "y": y, "tr": tr, "va": va, "te": te, "prep": prep}


class Modele(nn.Module):
    def __init__(self, n_in, hidden, n_classes, kind):
        super().__init__()
        cellule = {"GRU": nn.GRU, "LSTM": nn.LSTM}[kind]
        self.rnn = cellule(n_in, hidden, batch_first=True)
        self.sortie = nn.Linear(hidden, n_classes)

    def forward(self, x):
        out, _ = self.rnn(x)
        return self.sortie(out[:, -1, :])


def predire(model, X):
    model.eval()
    with torch.no_grad():
        p = torch.softmax(model(torch.tensor(X, dtype=torch.float32)), dim=1)
    return p.numpy()


def entrainer(kind, seed, X, y, tr, va):
    torch.manual_seed(seed)
    np.random.seed(seed)
    poids = torch.tensor(
        len(y[tr])
        / (len(NIVEAUX) * np.bincount(y[tr], minlength=len(NIVEAUX)).clip(1)),
        dtype=torch.float32,
    )
    model = Modele(X.shape[2], HIDDEN, len(NIVEAUX), kind)
    opt = torch.optim.Adam(model.parameters(), lr=LR)
    perte = nn.CrossEntropyLoss(weight=poids)
    loader = DataLoader(
        TensorDataset(torch.tensor(X[tr], dtype=torch.float32), torch.tensor(y[tr])),
        batch_size=BATCH,
        shuffle=True,
    )

    meilleur, attente, etat = -1, 0, None
    for _ in range(EPOCHS):
        model.train()
        for xb, yb in loader:
            opt.zero_grad()
            perte(model(xb), yb).backward()
            opt.step()
        f1_val = f1_score(y[va], predire(model, X[va]).argmax(1), average="macro")
        if f1_val > meilleur:
            meilleur, attente = f1_val, 0
            etat = {k: v.clone() for k, v in model.state_dict().items()}
        else:
            attente += 1
            if attente >= PATIENCE:
                break
    model.load_state_dict(etat)
    return model, meilleur


def evaluer_modele(kind, donnees):
    X, y, tr, va, te = (
        donnees["X"],
        donnees["y"],
        donnees["tr"],
        donnees["va"],
        donnees["te"],
    )
    runs = []
    for seed in SEEDS:
        model, f1_val = entrainer(kind, seed, X, y, tr, va)
        pred = predire(model, X[te]).argmax(1)
        f1_test = f1_score(y[te], pred, average="macro")
        runs.append(
            {
                "seed": seed,
                "model": model,
                "f1_val": f1_val,
                "f1_test": f1_test,
                "pred": pred,
            }
        )
        print(
            f"{kind} | graine {seed} : F1 val = {f1_val:.3f} | F1 test = {f1_test:.3f}"
        )

    meilleur_run = max(runs, key=lambda r: r["f1_val"])
    torch.save(meilleur_run["model"].state_dict(), f"modele_{kind}.pt")
    return {
        "kind": kind,
        "model": meilleur_run["model"],
        "seed": meilleur_run["seed"],
        "pred_test": meilleur_run["pred"],
        "f1_val_moy": float(np.mean([r["f1_val"] for r in runs])),
        "f1_test_moy": float(np.mean([r["f1_test"] for r in runs])),
        "f1_test_std": float(np.std([r["f1_test"] for r in runs])),
        "f1_test_meilleur": meilleur_run["f1_test"],
    }


def entrainer_gru(donnees):
    return evaluer_modele("GRU", donnees)


def entrainer_lstm(donnees):
    return evaluer_modele("LSTM", donnees)


def comparer(res_gru, res_lstm, donnees):
    resultats = {"GRU": res_gru, "LSTM": res_lstm}
    for kind, r in resultats.items():
        print(
            f"{kind} : meilleure graine = {r['seed']} | F1 val moyen = {r['f1_val_moy']:.3f} | "
            f"F1 test moyen = {r['f1_test_moy']:.3f} ± {r['f1_test_std']:.3f}"
        )

    resultats["meilleur"] = (
        "GRU" if res_gru["f1_val_moy"] >= res_lstm["f1_val_moy"] else "LSTM"
    )
    print("Meilleur modèle :", resultats["meilleur"])

    y_te = donnees["y"][donnees["te"]]
    pred = resultats[resultats["meilleur"]]["pred_test"]
    print(classification_report(y_te, pred, target_names=NIVEAUX, zero_division=0))
    print(confusion_matrix(y_te, pred))
    return resultats


def choisir_modele(resultats, modele="meilleur"):
    kind = resultats["meilleur"] if modele == "meilleur" else modele.upper()
    return kind, resultats[kind]["model"]


def predirePatient(resultats, mesures, prep, modele="meilleur"):
    kind, model = choisir_modele(resultats, modele)
    T, med, mu, sd = prep["T"], prep["med"], prep["mu"], prep["sd"]

    df = pd.DataFrame(mesures, columns=FEATURES, dtype=float).ffill()
    a = df.to_numpy(dtype=np.float32)
    if len(a) < T:
        a = np.vstack([a, np.repeat(a[-1:], T - len(a), axis=0)])
    a = a[:T]
    a = np.where(np.isnan(a), med, a)
    a = (a - mu) / sd

    proba = predire(model, a[None, :, :])[0]
    classe = NIVEAUX[int(proba.argmax())]
    return classe, {n: float(p) for n, p in zip(NIVEAUX, proba)}


def DL_Risk(nom, mesures, resultats, prep, modele="meilleur"):
    kind, _ = choisir_modele(resultats, modele)
    classe, probas = predirePatient(resultats, mesures, prep, modele)
    return {"Patient": nom, "Modele": kind, "DL_Risk": classe, "Probabilites": probas}


